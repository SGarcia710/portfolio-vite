export function drawBitmap(ctx: CanvasRenderingContext2D, bitmap: string[], x: number, y: number, scale = 1) {
  bitmap.forEach((row, rowIndex) => {
    for (let col = 0; col < row.length; col += 1) {
      const cell = row[col];
      if (cell === ' ') continue;
      ctx.fillStyle = cell === '#' ? '#000' : '#fff';
      ctx.fillRect(Math.round(x + col * scale), Math.round(y + rowIndex * scale), scale, scale);
    }
  });
}
